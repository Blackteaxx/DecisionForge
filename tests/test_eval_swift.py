def test_offline_sample_scoring_does_not_need_image_bytes(tmp_path):
    from decisionforge.eval.data import load_samples

    data = {
        "schema_version": "decisionforge.eval.v1",
        "id": "one",
        "group_id": "one",
        "split": "test",
        "subset": "image",
        "request": {
            "state": "context",
            "images": [{"path": "gone.png", "sha256": "0" * 64}],
            "questions": {
                "decision": {
                    "type": "choice",
                    "instructions": "pick",
                    "criteria": {"a": "first", "b": "second"},
                }
            },
        },
        "target": {"kind": "hard", "value": "a"},
        "metadata": {},
    }
    path = tmp_path / "data.jsonl"
    path.write_text(json.dumps(data) + "\n")
    assert load_samples(path, resolve_media=False)[0].request.images[0].path == "gone.png"
    with pytest.raises(ValueError, match="Media file does not exist"):
        load_samples(path)


@pytest.mark.parametrize("field", ["adapter", "ms_swift"])
def test_incomplete_lineage_is_rejected(tmp_path, field):
    root = artifact_at(tmp_path / "model")
    marker = root / "dforge_swift_artifact.json"
    value = json.loads(marker.read_text())
    value["lineage"].pop(field)
    marker.write_text(json.dumps(value))
    with pytest.raises(ValueError, match="lineage is incomplete"):
        validate_artifact(root)
