def artifact_at(root):
    root.mkdir()
    files = {}
    for name in (
        "adapter_config.json",
        "adapter_model.safetensors",
        "scoring_head.json",
        "scoring_head.safetensors",
        "head.pt",
        "ord.pt",
        "head_meta.json",
        "new_tok_emb.pt",
    ):
        data = b"{}" if name.endswith(".json") else b"unit-test-artifact"
        (root / name).write_bytes(data)
        files[name] = hashlib.sha256(data).hexdigest()
    (root / "dforge_swift_artifact.json").write_text(
        json.dumps(
            {
                "schema_version": "decisionforge.swift.omnijev.v1",
                "files": files,
                "lineage": {
                    "base_model": {
                        "name": "Qwen/Qwen3.5-4B",
                        "revision": "851bf6e806efd8d0a36b00ddf55e13ccb7b8cd0a",
                    },
                    "adapter": {
                        "name": "tinnel123/OmniJev",
                        "revision": "91248107b7f5230bd5715db2e62e83c9a72fcd81",
                    },
                    "ms_swift": "680df5c670d7e8add906ac49381d603869410612",
                },
            }
        )
    )
    return root


def test_typed_config_and_no_parallel_worker():
    c = EvalConfig(data={"path": "x"}, model={"adapter": "swift_local", "path": "cp"})
    assert c.model.model == "cp" and c.model.precision == "bf16"
    with pytest.raises(ValueError, match="concurrency"):
        EvalConfig(
            data={"path": "x"},
            model={"adapter": "swift_local", "path": "cp"},
            execution={"concurrency": 2},
        )
    with pytest.raises(ValueError):
        EvalConfig(
            data={"path": "x"}, model={"adapter": "swift_local", "path": "cp", "model_type": "laya"}
        )


def test_adapter_rechecks_full_raw_columns():
    c = EvalConfig(data={"path": "x"}, model={"adapter": "swift_local", "path": "cp"})
    q = Question(type="choice", criteria={"x": "one", "y": "two"})
    answer, abstain = readout(q, [0.2, 0.3, 0.5])
    raw = {
        "answers": {"decision": answer},
        "swift": {
            "probability_contract": PROBABILITY_CONTRACT,
            "columns": [
                {
                    "question_id": "decision",
                    "native": [{"probs": [0.2, 0.3, 0.5], "index": 2}],
                    "abstain_probability": abstain,
                }
            ],
        },
    }
    adapter = SwiftAdapter(c.model, c.execution)
    assert adapter.response_answer(raw, q)["probabilities"] == pytest.approx({"x": 0.4, "y": 0.6})
    corrupted = copy.deepcopy(raw)
    corrupted["answers"]["decision"]["probabilities"]["x"] = 0.9
    with pytest.raises(ValueError, match="differs"):
        adapter.response_answer(corrupted, q)


def test_chat_malformed_output_is_retained():
    c = EvalConfig(
        data={"path": "x"}, model={"adapter": "swift_chat_local", "path": "Qwen/Qwen3.5-4B"}
    )
    a = SwiftAdapter(c.model, c.execution)
    raw = {
        "choices": [
            {"message": {"role": "assistant", "content": "not JSON"}, "finish_reason": "stop"}
        ]
    }
    before = copy.deepcopy(raw)
    with pytest.raises(ValueError):
        a.response_answer(raw, Question(type="choice", criteria={"a": "first", "b": "second"}))
    assert raw == before


@pytest.mark.parametrize("generated", ["valid", "not JSON", "generated thinking"])
def test_chat_decodes_native_generated_ids_without_sdk_prompt_prefix(generated):
    from types import SimpleNamespace

    pytest.importorskip("swift")
    from swift.template.base import Template

    from decisionforge.training.backends.swift_runtime import Runtime

    body = json.dumps(
        {
            "answers": {
                "decision": {
                    "type": "choice",
                    "choice": "a",
                    "confidence": 0.8,
                    "probabilities": {"a": 0.8, "b": 0.2},
                }
            }
        }
    )
    if generated == "not JSON":
        body = "not JSON"
    elif generated == "generated thinking":
        body = "<think>generated by the model</think>" + body
    prefix = "<think>\n\n</think>\n\n"

    class Tokenizer:
        def decode(self, ids, **kwargs):
            assert ids == [123, 456]
            return body

    template = SimpleNamespace(
        tokenizer=Tokenizer(),
        skip_stop_tokens=lambda ids, finished: ids,
        _get_response_prefix=lambda inputs: prefix,
    )
    template.decode_generate_ids = lambda ids, **kwargs: Template.decode_generate_ids(
        template, ids, **kwargs
    )
    sdk_content = template.decode_generate_ids([123, 456])
    assert sdk_content == prefix + body

    def infer(requests, request_config, **kwargs):
        assert request_config.return_details and request_config.temperature == 0
        assert request_config.max_tokens == 4096
        return [
            SimpleNamespace(
                choices=[
                    SimpleNamespace(
                        token_ids=[123, 456],
                        finish_reason="stop",
                        message=SimpleNamespace(content=sdk_content),
                    )
                ]
            )
        ]

    runtime = Runtime.__new__(Runtime)
    runtime.engine = SimpleNamespace(template=template, infer=infer)
    public = {
        "state": "context",
        "questions": {
            "decision": {
                "type": "choice",
                "criteria": {"a": "first", "b": "second"},
            }
        },
    }
    raw = runtime.predict_chat(public, [{"images": []}])
    assert raw["choices"][0]["message"]["content"] == body
    assert raw["swift_chat"]["sdk_response_content"] == sdk_content
    assert raw["swift_chat"]["generated_token_ids"] == [123, 456]
    config = EvalConfig(
        data={"path": "unused"},
        model={
            "adapter": "swift_chat_local",
            "path": "Qwen/Qwen3.5-4B",
        },
    )
    adapter = SwiftAdapter(config.model, config.execution)
    question = Question.model_validate(public["questions"]["decision"])
    if generated == "valid":
        assert adapter.response_answer(raw, question)["probabilities"] == {"a": 0.8, "b": 0.2}
    else:
        with pytest.raises(ValueError):
            adapter.response_answer(raw, question)


def test_artifact_tampering_fails_before_model_import(tmp_path):
    root = artifact_at(tmp_path / "model")
    assert validate_artifact(root) == root
    (root / "scoring_head.json").write_text('{"temperature":2}')
    with pytest.raises(ValueError, match="hash mismatch"):
        validate_artifact(root)


